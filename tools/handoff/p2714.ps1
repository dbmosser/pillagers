$new = "  now:'v27.14: The pickup stack on the right edge now shows six rows instead of four. Check 27.14 fails on v27.13',"
$s = [regex]::Replace($s, $pat, { param($m) $new })
if (([regex]::Matches($s, "(?m)^  now:'")).Count -ne 1) { throw "more than one now key in DEVNOW" }
