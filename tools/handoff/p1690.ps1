if ($c -ne 1) { throw "DEVNOW now line matched $c times, expected 1" }
$new = "  now:'v16.90: THE BUILD SAYS CALL FOR EXTRACTION EVERYWHERE. The full sweep on v16.88 found the old verb phrase in a comment written at v16.72; check 9.59 reads every line of the build for it. The comment now says call for extraction. Nothing the player sees changes. Check 16.90 fails on v16.89',"
$s = [regex]::Replace($s, $pat, { param($m) $new })
if (([regex]::Matches($s, "(?m)^  now:'")).Count -ne 1) { throw "more than one now key in DEVNOW" }
